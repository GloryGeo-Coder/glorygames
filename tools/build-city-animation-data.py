"""Read unmodified alpha to record City Quest's animation crops. Dev: Pillow/numpy/scipy."""
from pathlib import Path
import hashlib,json,statistics
import numpy as np
from scipy import ndimage
from PIL import Image
root=Path(__file__).resolve().parents[1]/'apps/web/public/games/city-quest-rise-of-the-guardian'
manifest=json.loads((root/'assets/animation/manifest.json').read_text());atlases={};originals={}
for item in manifest['assets']:
 p=root/'assets/animation'/item['file'];im=Image.open(p);a=np.asarray(im.getchannel('A'))
 labels,_=ndimage.label(a>180);counts=np.bincount(labels.ravel());counts[0]=0;ids=np.flatnonzero(counts>1500)
 cols=6 if item['file'].startswith('guardian') else 4;assert len(ids)==cols*6
 distance,nearest=ndimage.distance_transform_edt(~np.isin(labels,ids),return_indices=True);owners=labels[nearest[0],nearest[1]]
 fg=(a>32)&(distance<=35);bodies=[]
 for i in ids:
  yy,xx=np.nonzero(fg&(owners==i));bodies.append([int(xx.min()),int(yy.min()),int(xx.max()+1),int(yy.max()+1),int(i)])
 bodies.sort(key=lambda b:(b[1]+b[3])/2);ordered=[]
 for row in range(6):ordered+=sorted(bodies[row*cols:row*cols+cols],key=lambda b:(b[0]+b[2])/2)
 frames=[]
 for x,y,r,b,i in ordered:
  crop=[max(0,x-2),max(0,y-2),min(im.width,r+2),min(im.height,b+2)];l,t,rr,bb=crop
  frames.append({'crop':[l,t,rr-l,bb-t],'content':[x,y,r-x,b-y]})
 groups={'hero_blue':(0,12),'hero_green':(12,12),'hero_shadow':(24,12)} if cols==6 else {'walker':(0,12),'boss_taxi':(12,12)}
 for kind,(start,count) in groups.items():
  clips={'idle':[0,2,3,True],'run':[2,6,10 if cols==6 else 7,True]}
  clips.update({'rise':[8,1,1,False],'fall':[9,1,1,False],'shoot':[10,1,1,False],'hurt':[11,1,1,False]} if cols==6 else {'windup':[8,1,1,False],'shoot':[9,1,1,False],'hurt':[10,1,1,False],'defeat':[11,1,1,False]})
  fs=frames[start:start+count];atlases[kind]={'url':'./assets/animation/'+item['file'],'width':im.width,'height':im.height,'referenceHeight':statistics.median(f['content'][3] for f in fs[:2]),'frames':fs,'clips':{k:dict(zip(['start','count','fps','loop'],v)) for k,v in clips.items()}}
 item.update(width=im.width,height=im.height,frames=len(frames),decoded_bytes=im.width*im.height*4,sha256=hashlib.sha256(p.read_bytes()).hexdigest())
# Stable crops remove the large transparent borders from all retained legacy props.
for p in (root/'assets/sprites').glob('*.png'):
 a=np.asarray(Image.open(p).convert('RGBA'))[:,:,3];yy,xx=np.nonzero(a>100)
 originals['./assets/sprites/'+p.name]=[int(xx.min()),int(yy.min()),int(xx.max()+1-xx.min()),int(yy.max()+1-yy.min())]
data={'version':'2.1','atlases':atlases,'originals':originals}
(root/'city-animation-data.js').write_text('/* Generated by tools/build-city-animation-data.py; original PNG bytes unchanged. */\n(function(r){"use strict";const d='+json.dumps(data,separators=(',',':'))+';if(typeof module==="object"&&module.exports)module.exports=d;else r.CityAnimationData=d;})(typeof window!=="undefined"?window:globalThis);\n')
(root/'assets/animation/manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')
print('Recorded 60 poses and',len(originals),'legacy sprite crops')
