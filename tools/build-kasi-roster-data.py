"""Record frame bounds from unmodified generated alpha. Dev-only: Pillow, numpy, scipy."""
from pathlib import Path
import hashlib,json,statistics
import numpy as np
from scipy import ndimage
from PIL import Image
root=Path(__file__).resolve().parents[1]/'apps/web/public/games/kasi-quest'
manifest_path=root/'assets/animation/roster-manifest.json'
manifest=json.loads(manifest_path.read_text())
atlases={}
for item in manifest['assets']:
 path=root/'assets/animation'/item['file'];im=Image.open(path)
 assert im.mode=='RGBA'
 alpha=np.asarray(im.getchannel('A'));labels,_=ndimage.label(alpha>180)
 counts=np.bincount(labels.ravel());counts[0]=0
 ids=np.flatnonzero(counts>2000)
 # Heads, braids and accessories may be disconnected from the main alpha component.
 # Assign nearby foreground to its closest body so no part is lost in a crop.
 body_mask=np.isin(labels,ids)
 distance,nearest=ndimage.distance_transform_edt(~body_mask,return_indices=True)
 owners=labels[nearest[0],nearest[1]]
 foreground=(alpha>32)&(distance<=64)
 assert len(ids)==20,(item['kind'],len(ids))
 frames=[]
 for index in ids:
  yy,xx=np.nonzero(foreground&(owners==index))
  x,y=int(xx.min()),int(yy.min());frames.append([x,y,int(xx.max())-x+1,int(yy.max())-y+1,int(index)])
 frames.sort(key=lambda f:f[1]+f[3]/2)
 ordered=[]
 for row in range(5):ordered+=sorted(frames[row*4:row*4+4],key=lambda f:f[0]+f[2]/2)
 reference=statistics.median(f[3] for f in ordered[:4]);padded=[]
 for x,y,w,h,index in ordered:
  left,top=max(0,x-3),max(0,y-3);right,bottom=min(im.width,x+w+3),min(im.height,y+h+3)
  frame={'crop':[left,top,right-left,bottom-top],'content':[x,y,w,h]}
  # Exclude foreign pixels at draw time, without changing the source images.
  region=owners[top:bottom,left:right]
  foreign=(region!=index)&foreground[top:bottom,left:right]
  if foreign.any():
   mask=ndimage.binary_dilation(foreign,iterations=2)&(region!=index)
   rectangles=[];active={}
   for row_index,row in enumerate(mask):
    edges=np.diff(np.pad(row.astype(np.int8),(1,1)));current={}
    for start,stop in zip(np.flatnonzero(edges==1),np.flatnonzero(edges==-1)):
     key=(int(start),int(stop-start));rect=active.get(key)
     if rect is None:rect=[int(start),row_index,int(stop-start),0];rectangles.append(rect)
     rect[3]+=1;current[key]=rect
    active=current
   frame['exclude']=rectangles
  padded.append(frame)
 clips={'idle':[0,4,5,True],'run':[4,4,9 if item['kind']=='sprinter' else 6,True],
        'windup':[8,4,9 if item['kind']=='sprinter' else 6,False],'shoot':[12,2,9,False],'hurt':[14,2,9,False],'defeat':[16,4,7,False]}
 atlases[item['kind']]={'url':'./assets/animation/'+item['file'],'width':im.width,'height':im.height,'referenceHeight':reference,'frames':padded,
  'clips':{key:dict(zip(['start','count','fps','loop'],v))for key,v in clips.items()}}
 item.update(width=im.width,height=im.height,frames=len(padded),decoded_bytes=im.width*im.height*4,sha256=hashlib.sha256(path.read_bytes()).hexdigest())
data={'version':'3.4','atlases':atlases}
s='/* Generated by tools/build-kasi-roster-data.py; source image bytes are unchanged. */\n'
s+='(function(root){"use strict";const data='+json.dumps(data,separators=(',',':'))+';\n'
s+='if(typeof module==="object"&&module.exports)module.exports=data;else root.KasiEnemyData=data;\n})(typeof window!=="undefined"?window:globalThis);\n'
(root/'kasi-enemy-data.js').write_text(s)
manifest_path.write_text(json.dumps(manifest,indent=2,ensure_ascii=False)+'\n')
print('Recorded 80 isolated new character poses; decoded bytes:',sum(x['decoded_bytes'] for x in manifest['assets']))
