"""Read the generated sprite alpha to record cell crops; never rewrite the PNGs."""
from pathlib import Path
import json
import numpy as np
from PIL import Image

ROOT=Path(__file__).resolve().parents[1]/'apps/web/public/games/fruit-slice'
def frames(file,cols,rows):
 im=Image.open(ROOT/file);alpha=np.array(im.getchannel('A'));result=[]
 for row in range(rows):
  for col in range(cols):
   x0=round(col*im.width/cols);x1=round((col+1)*im.width/cols)
   y0=round(row*im.height/rows);y1=round((row+1)*im.height/rows)
   ys,xs=np.nonzero(alpha[y0:y1,x0:x1]>30)
   assert len(xs)>300,(file,row,col)
   x=x0+int(xs.min());y=y0+int(ys.min());w=int(xs.max()-xs.min()+1);h=int(ys.max()-ys.min()+1)
   result.append([x,y,w,h])
 return result
def main():
 sprites={}
 for file,names in [('whole-a.png',['apple','orange','watermelon']),('whole-b.png',['kiwi','pineapple','bomb'])]:
  url='./assets/animation/'+file;crops=frames('assets/animation/'+file,4,3)
  for row,name in enumerate(names):sprites[name]={'url':url,'frames':crops[row*4:row*4+4]}
 cuts=frames('assets/animation/cuts.png',5,2)
 for i,name in enumerate(['apple','orange','watermelon','kiwi','pineapple']):sprites[name]['cuts']={'url':'./assets/animation/cuts.png','frames':[cuts[i],cuts[i+5]]}
 (ROOT/'fruit-animation-data.js').write_text('/* Alpha-derived crops; generated by tools/build-fruit-animation-data.py. */\n(function(root){const data='+json.dumps(sprites,separators=(',',':'))+';if(typeof module==="object"&&module.exports)module.exports=data;else root.FruitFrames=data;})(typeof window!=="undefined"?window:globalThis);\n')
 print('24 animation poses and 10 cut halves indexed.')
if __name__=='__main__':main()
